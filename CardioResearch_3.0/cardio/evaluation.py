"""Read-only aggregate diagnostics shared with the hosted application.

This module never loads patient rows or fits models. Reports are generated by
deployment/cardio-site/scripts/build-evaluation.py and evaluate-transfer.mjs.
"""
import csv
import json
from io import StringIO


def evaluation_payload(report, dataset):
    if dataset not in ('brfss', 'uci'):
        raise ValueError('Unknown dataset')
    return dict(report['datasets'][dataset], schema_version=report['schema_version'],
                created=report['created'], sources=report['sources'], methods=report['methods'])


def evaluation_csv(payload):
    stream = StringIO(newline='')
    writer = csv.writer(stream)
    writer.writerow(['dataset', 'model', 'evaluation', 'n', 'threshold', 'weighting',
                     'metric', 'value', 'ci_lower', 'ci_upper', 'interval_method'])
    context = [payload['dataset'], payload['model'], payload['evaluation'],
               payload['n'], payload['threshold'], 'unweighted']
    for metric, value in payload['metrics'].items():
        ci = payload.get('intervals', {}).get(metric)
        writer.writerow(context + [metric, value, ci[0] if ci else '', ci[1] if ci else '',
            'Wilson 95%; fixed predictions; sampling/design limitations apply' if ci else ''])
    (tn, fp), (fn, tp) = payload['confusion']
    for metric, value in [('TN', tn), ('FP', fp), ('FN', fn), ('TP', tp)]:
        writer.writerow(context + [metric, value])
    return stream.getvalue().encode('utf-8-sig')


def register_evaluation_routes(app, reports_dir):
    from fastapi import HTTPException
    from fastapi.responses import Response

    def read(name):
        path = reports_dir / name
        if not path.exists():
            raise HTTPException(503, 'Диагностический отчёт ещё не создан')
        return json.loads(path.read_text(encoding='utf-8'))

    def payload(ds):
        if ds not in ('brfss', 'uci'):
            raise HTTPException(400, 'Неизвестный набор данных')
        return evaluation_payload(read('evaluation.json'), ds)

    @app.get('/api/evaluation/{ds}')
    def evaluation(ds: str):
        return payload(ds)

    @app.get('/api/evaluation-export/{ds}')
    def export(ds: str, format: str = 'json'):
        result = payload(ds)
        if format not in ('csv', 'json'):
            raise HTTPException(422, 'Выберите json или csv')
        body = evaluation_csv(result) if format == 'csv' else json.dumps(result, ensure_ascii=False, indent=2).encode('utf-8')
        return Response(body, media_type='text/csv' if format == 'csv' else 'application/json',
                        headers={'Content-Disposition': f'attachment; filename="{ds}_evaluation.{format}"', 'Cache-Control': 'no-store'})

    @app.get('/api/transfer/uci')
    def transfer():
        return read('transfer.json')

    @app.get('/api/disagreement/uci')
    def disagreement():
        return read('disagreement.json')

    @app.get('/api/temporal/brfss')
    def temporal():
        return read('temporal.json')

    @app.get('/api/transfer-export/uci')
    def transfer_export():
        return Response(json.dumps(read('transfer.json'), ensure_ascii=False, indent=2).encode('utf-8'),
                        media_type='application/json', headers={'Content-Disposition': 'attachment; filename="uci_transfer.json"', 'Cache-Control': 'no-store'})
