def field_label(field,lang='ru'):
    return FIELD_KK[field['name']] if lang=='kk' else field['label']


def displayed_value(field,value,lang='ru'):
    if value is None:return REPORT_TEXT[lang]['missing']
    if field['kind']!='category':return str(value)
    label=next((option['label'] for option in field['options'] if option['value']==value),str(value))
    return OPTION_KK.get(label,label) if lang=='kk' else label


def disclaimer(dataset,lang='ru'):
    return DISCLAIMERS[lang][dataset]
